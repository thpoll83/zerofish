#!/usr/bin/env python3
"""Generate the Chess Coach launcher icon and header logo.

The mark is a 4x4 checkerboard of rounded squares, the light squares lit in a
green -> cyan sweep on a dark body, with a camera lens ring over its centre: the
app watches a real board. The same geometry serves every icon, so a change here
reaches all of them on the next run.

Written (Android vector drawables, so one file serves every density):
  res/drawable/ic_launcher_background.xml   the dark body, full bleed
  res/drawable/ic_launcher_foreground.xml   board and lens
  res/drawable/ic_launcher_monochrome.xml   lit squares and lens in white, for themed icons (API 33+)
  res/drawable/ic_logo.xml                  board and lens on a transparent ground, for the header
  res/mipmap-anydpi/ic_launcher{,_round}.xml

    python3 app/tools/gen_launcher_icon.py                 # write the drawables
    python3 app/tools/gen_launcher_icon.py --sheet X.png   # preview sheet (Pillow), write nothing
"""
import argparse
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parent / "src" / "main" / "res"

# Adaptive icons draw on a 108dp canvas and launchers mask it to anything from a
# circle to a squircle; only a 66dp circle is guaranteed visible. A 52dp board puts
# its corner squares 37dp from the centre, inside every mask.
CANVAS = 108.0
BOARD = 52.0
N = 4
GAP = 1.4
RADIUS = 1.8

LENS_R = 15.5       # outer radius of the ring
LENS_STROKE = 3.2
PUPIL_R = 4.0

KEY_FROM, KEY_TO = "#16A34A", "#22D3EE"
BODY_TOP, BODY_BOTTOM = "#182135", "#080C16"
GHOST = "#14FFFFFF"   # the dark squares: a hint of white on the body
WHITE = "#FFFFFFFF"

AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def squares(size=CANVAS, board=BOARD):
    """(x, y, side, lit) per square, the board centred on a size-unit canvas."""
    pitch = board / N
    side = pitch - GAP
    off = (size - board) / 2 + GAP / 2
    for r in range(N):
        for c in range(N):
            yield off + c * pitch, off + r * pitch, side, (r + c) % 2 == 0


def rrect(x, y, w, r):
    s = w - 2 * r
    return (f"M{x + r:.2f},{y:.2f}h{s:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f}"
            f"v{s:.2f}a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{r:.2f}h{-s:.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{-r:.2f}v{-s:.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{-r:.2f}z")


def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1 0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1 0 {-2 * r:.2f},0z"


def lens_paths(size=CANVAS, scale=1.0):
    c = size / 2
    ring = circle(c, c, LENS_R * scale) + circle(c, c, (LENS_R - LENS_STROKE) * scale)
    pupil = circle(c, c, PUPIL_R * scale)
    return ring, pupil


def vector(size, body, dp=None):
    dp = dp or size
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by app/tools/gen_launcher_icon.py. Do not edit. -->\n'
            f'<vector {ANDROID} {AAPT}\n'
            f'    android:width="{dp:g}dp" android:height="{dp:g}dp"\n'
            f'    android:viewportWidth="{size:g}" android:viewportHeight="{size:g}">\n'
            f'{body}</vector>\n')


def gradient_path(d, x0, y0, x1, y1, stops):
    items = "".join(f'                <item android:offset="{o}" android:color="{c}"/>\n' for o, c in stops)
    return (f'    <path android:pathData="{d}">\n'
            f'        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="linear" android:startX="{x0:.2f}" android:startY="{y0:.2f}"\n'
            f'                android:endX="{x1:.2f}" android:endY="{y1:.2f}">\n'
            f'{items}'
            f'            </gradient>\n'
            f'        </aapt:attr>\n'
            f'    </path>\n')


def mark_body(size=CANVAS, board=BOARD):
    """The board and the lens, in colour, for the foreground and the header logo."""
    sq = list(squares(size, board))
    lit = "".join(rrect(x, y, s, RADIUS * board / BOARD) for x, y, s, on in sq if on)
    ghost = "".join(rrect(x, y, s, RADIUS * board / BOARD) for x, y, s, on in sq if not on)
    a0 = (size - board) / 2
    a1 = a0 + board
    body = f'    <path android:pathData="{ghost}" android:fillColor="{GHOST}"/>\n'
    body += gradient_path(lit, a0, a0, a1, a1, [(0, KEY_FROM), (1, KEY_TO)])
    # a top-lit sheen on each lit square (a vector gradient is in path space, so one per square)
    for x, y, s, on in sq:
        if on:
            body += gradient_path(rrect(x, y, s, RADIUS * board / BOARD), 0, y, 0, y + s,
                                  [(0, "#4DFFFFFF"), (0.55, "#0AFFFFFF"), (1, "#30000018")])
    ring, pupil = lens_paths(size, board / BOARD)
    body += f'    <path android:pathData="{ring}" android:fillColor="{WHITE}" android:fillType="evenOdd"/>\n'
    body += f'    <path android:pathData="{pupil}" android:fillColor="{WHITE}"/>\n'
    return body


def background_xml():
    d = f"M0,0h{CANVAS:g}v{CANVAS:g}h{-CANVAS:g}z"
    return vector(CANVAS, gradient_path(d, 0, 0, 0, CANVAS, [(0, BODY_TOP), (1, BODY_BOTTOM)]))


def foreground_xml():
    return vector(CANVAS, mark_body())


def monochrome_xml():
    lit = "".join(rrect(x, y, s, RADIUS) for x, y, s, on in squares() if on)
    ring, pupil = lens_paths()
    return vector(CANVAS, f'    <path android:pathData="{lit}" android:fillColor="{WHITE}"/>\n'
                          f'    <path android:pathData="{ring}" android:fillColor="{WHITE}" android:fillType="evenOdd"/>\n'
                          f'    <path android:pathData="{pupil}" android:fillColor="{WHITE}"/>\n')


def logo_xml():
    # The header logo: the board fills a 48dp canvas (no body, no mask to allow for).
    return vector(48, mark_body(48, 46), dp=48)


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tools/gen_launcher_icon.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def outputs():
    return {
        RES / "drawable" / "ic_launcher_background.xml": background_xml(),
        RES / "drawable" / "ic_launcher_foreground.xml": foreground_xml(),
        RES / "drawable" / "ic_launcher_monochrome.xml": monochrome_xml(),
        RES / "drawable" / "ic_logo.xml": logo_xml(),
        RES / "mipmap-anydpi" / "ic_launcher.xml": ADAPTIVE,
        RES / "mipmap-anydpi" / "ic_launcher_round.xml": ADAPTIVE,
    }


# --- preview with Pillow: the same geometry rasterised under the launcher masks ---

def render(px, mask, ground=True, size=CANVAS, board=BOARD, white=False):
    from PIL import Image, ImageDraw

    ss = 4
    w = px * ss
    k = w / size
    img = Image.new("RGBA", (w, w), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def hexrgb(h, a=255):
        h = h.lstrip("#")
        if len(h) == 8:
            a, h = int(h[:2], 16), h[2:]
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (a,)

    if ground:
        # vertical body gradient
        for yy in range(w):
            t = yy / w
            top, bot = hexrgb(BODY_TOP), hexrgb(BODY_BOTTOM)
            col = tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3)) + (255,)
            d.line([(0, yy), (w, yy)], fill=col)
    sq = list(squares(size, board))
    a0 = (size - board) / 2
    for x, y, s, on in sq:
        box = [x * k, y * k, (x + s) * k, (y + s) * k]
        if on:
            if white:
                col = (255, 255, 255, 255)
            else:
                t = ((x + s / 2 - a0) + (y + s / 2 - a0)) / (2 * board)
                f, to = hexrgb(KEY_FROM), hexrgb(KEY_TO)
                col = tuple(int(f[i] + (to[i] - f[i]) * t) for i in range(3)) + (255,)
            d.rounded_rectangle(box, radius=RADIUS * k * board / BOARD, fill=col)
        elif not white:
            layer = Image.new("RGBA", (w, w), (0, 0, 0, 0))
            ImageDraw.Draw(layer).rounded_rectangle(box, radius=RADIUS * k * board / BOARD, fill=(255, 255, 255, 20))
            img.alpha_composite(layer)
            d = ImageDraw.Draw(img)
    c = size / 2 * k
    sc = board / BOARD
    d.ellipse([c - LENS_R * sc * k, c - LENS_R * sc * k, c + LENS_R * sc * k, c + LENS_R * sc * k], outline=(255, 255, 255, 255), width=int(LENS_STROKE * sc * k))
    d.ellipse([c - PUPIL_R * sc * k, c - PUPIL_R * sc * k, c + PUPIL_R * sc * k, c + PUPIL_R * sc * k], fill=(255, 255, 255, 255))
    if mask:
        m = Image.new("L", (w, w), 0)
        md = ImageDraw.Draw(m)
        inset = 18 * k
        if mask == "circle":
            md.ellipse([inset, inset, w - inset, w - inset], fill=255)
        elif mask == "squircle":
            md.rounded_rectangle([inset, inset, w - inset, w - inset], radius=24 * k, fill=255)
        else:
            md.rounded_rectangle([inset, inset, w - inset, w - inset], radius=6 * k, fill=255)
        img.putalpha(m)
        img = img.crop((int(inset), int(inset), int(w - inset), int(w - inset)))
    return img.resize((px if not mask else int(px * 72 / 108), ) * 2, Image.LANCZOS)


def sheet(path):
    from PIL import Image, ImageDraw

    tiles = []
    for mask in ("circle", "squircle", "square"):
        tiles += [render(288, mask), render(72, mask)]
    header = Image.new("RGBA", (260, 120), (0, 0, 0, 255))
    header.alpha_composite(render(72, None, ground=False, size=48, board=46), (24, 24))
    ImageDraw.Draw(header).text((110, 40), "Chess Coach", fill=(255, 255, 255, 255))
    ImageDraw.Draw(header).text((110, 60), "Your move", fill=(203, 213, 225, 255))
    tiles.append(header)
    w = sum(t.width for t in tiles) + 16 * (len(tiles) + 1)
    img = Image.new("RGBA", (w, 240), (241, 243, 244, 255))
    x = 16
    d = ImageDraw.Draw(img)
    for t, label in zip(tiles, ["circle 192", "48", "squircle 192", "48", "square 192", "48", "header"]):
        img.alpha_composite(t, (x, 16 + (192 - t.height) // 2))
        d.text((x, 218), label, fill=(51, 51, 51, 255))
        x += t.width + 16
    img.save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--sheet", help="write a preview sheet to this PNG and nothing else")
    args = ap.parse_args()
    if args.sheet:
        sheet(args.sheet)
        return
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path.relative_to(HERE.parent.parent))


if __name__ == "__main__":
    main()
